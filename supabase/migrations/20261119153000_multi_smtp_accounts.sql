-- Multiple SMTP sender accounts. SMTP passwords are AES-256-GCM encrypted by the server.
create table if not exists public.smtp_accounts (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  host text not null,
  port integer not null default 587 check (port between 1 and 65535),
  secure boolean not null default false,
  username text not null,
  password_encrypted text not null,
  from_name text,
  is_active boolean not null default true,
  created_by bigint references public.user_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists smtp_accounts_email_unique on public.smtp_accounts (lower(email));
alter table public.smtp_accounts enable row level security;
drop policy if exists "smtp_accounts_no_direct_access" on public.smtp_accounts;
create policy "smtp_accounts_no_direct_access" on public.smtp_accounts
for all to authenticated using (false) with check (false);
-- All reads and writes are performed by authenticated server routes with the service role.
