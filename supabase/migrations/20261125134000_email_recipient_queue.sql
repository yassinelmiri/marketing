-- Normalize campaign recipients so workers fetch only the next delivery batch.
begin;
create table if not exists public.email_campaign_recipients (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.email_campaigns(id) on delete cascade,
  email text not null,
  status text not null default 'pending' check (status in ('pending','sent','failed','skipped')),
  error_message text,
  smtp_account_id bigint references public.smtp_accounts(id) on delete set null,
  processed_at timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists email_campaign_recipients_campaign_email_unique
  on public.email_campaign_recipients(campaign_id, lower(email));
create index if not exists email_campaign_recipients_queue_idx
  on public.email_campaign_recipients(campaign_id, status, id);
alter table public.email_campaign_recipients enable row level security;
drop policy if exists email_campaign_recipients_no_direct_access on public.email_campaign_recipients;
create policy email_campaign_recipients_no_direct_access on public.email_campaign_recipients
  for all to authenticated using (false) with check (false);
commit;
