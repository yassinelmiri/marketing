-- Email marketing: templates, campaign settings, per-recipient tracking and global suppressions.
begin;
alter table public.email_campaigns
  add column if not exists reply_to text,
  add column if not exists template_id bigint,
  add column if not exists tracking_opens boolean not null default true,
  add column if not exists tracking_clicks boolean not null default true,
  add column if not exists batch_size integer not null default 50,
  add column if not exists batch_delay_seconds integer not null default 5,
  add column if not exists draft boolean not null default false;
create table if not exists public.email_templates (
  id bigint generated by default as identity primary key,
  name text not null,
  subject text not null default '',
  html_content text not null default '',
  created_by bigint references public.user_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists email_templates_created_at_idx on public.email_templates(created_at desc);
alter table public.email_templates enable row level security;
drop policy if exists "email_templates_no_direct_access" on public.email_templates;
create policy "email_templates_no_direct_access" on public.email_templates for all to authenticated using(false) with check(false);
create table if not exists public.email_campaign_events (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.email_campaigns(id) on delete cascade,
  recipient_email text not null,
  event_type text not null check(event_type in ('open','click','bounce')),
  target_url text,
  occurred_at timestamptz not null default now()
);
create index if not exists email_campaign_events_campaign_idx on public.email_campaign_events(campaign_id,event_type);
create index if not exists email_campaign_events_recipient_idx on public.email_campaign_events(campaign_id,recipient_email);
alter table public.email_campaign_events enable row level security;
drop policy if exists "email_campaign_events_no_direct_access" on public.email_campaign_events;
create policy "email_campaign_events_no_direct_access" on public.email_campaign_events for all to authenticated using(false) with check(false);
create table if not exists public.email_unsubscribes (
  id bigint generated by default as identity primary key,
  email text not null,
  reason text,
  campaign_id bigint references public.email_campaigns(id) on delete set null,
  unsubscribed_at timestamptz not null default now()
);
create unique index if not exists email_unsubscribes_email_unique on public.email_unsubscribes(lower(email));
alter table public.email_unsubscribes enable row level security;
drop policy if exists "email_unsubscribes_no_direct_access" on public.email_unsubscribes;
create policy "email_unsubscribes_no_direct_access" on public.email_unsubscribes for all to authenticated using(false) with check(false);
commit;
