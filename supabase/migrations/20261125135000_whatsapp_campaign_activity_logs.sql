-- Audit trail for user-confirmed WhatsApp Web assisted campaign actions.
begin;
create table if not exists public.whatsapp_campaign_activity_logs (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.whatsapp_campaigns(id) on delete cascade,
  recipient_id bigint references public.whatsapp_campaign_recipients(id) on delete set null,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  event_type text not null check (event_type in ('recipient_status','campaign_status','message_updated')),
  old_status text,
  new_status text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists whatsapp_campaign_activity_logs_campaign_idx
  on public.whatsapp_campaign_activity_logs(campaign_id, created_at desc);
alter table public.whatsapp_campaign_activity_logs enable row level security;
drop policy if exists whatsapp_campaign_activity_logs_no_direct_access on public.whatsapp_campaign_activity_logs;
create policy whatsapp_campaign_activity_logs_no_direct_access on public.whatsapp_campaign_activity_logs
  for all to authenticated using (false) with check (false);
commit;
