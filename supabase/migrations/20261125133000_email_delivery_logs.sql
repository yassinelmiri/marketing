-- Append-only delivery audit trail. SMTP credentials and recipient payloads stay server-side.
begin;
create table if not exists public.email_delivery_logs (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.email_campaigns(id) on delete cascade,
  recipient_email text not null,
  status text not null check (status in ('sent','failed','skipped')),
  error_message text,
  smtp_account_id bigint references public.smtp_accounts(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists email_delivery_logs_campaign_created_idx
  on public.email_delivery_logs(campaign_id, created_at desc);
create index if not exists email_delivery_logs_recipient_idx
  on public.email_delivery_logs(lower(recipient_email), created_at desc);
alter table public.email_delivery_logs enable row level security;
drop policy if exists email_delivery_logs_no_direct_access on public.email_delivery_logs;
create policy email_delivery_logs_no_direct_access on public.email_delivery_logs
  for all to authenticated using (false) with check (false);
commit;
