-- Campaign assignments to workspace members
create table if not exists public.campagne_membres (
  id bigint generated by default as identity primary key,
  campagne_id bigint not null references public.campagnes(id) on delete cascade,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  date_ajout timestamptz not null default now(),
  unique (campagne_id, user_id)
);

create index if not exists campagne_membres_user_idx on public.campagne_membres(user_id);
create index if not exists campagne_membres_campaign_idx on public.campagne_membres(campagne_id);

alter table public.campagne_membres enable row level security;

drop policy if exists "campaign members read own assignments" on public.campagne_membres;
create policy "campaign members read own assignments"
on public.campagne_membres for select
using (
  exists (
    select 1 from public.user_profiles p
    where p.id = campagne_membres.user_id
      and p.auth_user_id = auth.uid()
  )
  or exists (
    select 1 from public.user_profiles p
    where p.auth_user_id = auth.uid() and p.role_id = 1
  )
);

drop policy if exists "admins manage campaign assignments" on public.campagne_membres;
create policy "admins manage campaign assignments"
on public.campagne_membres for all
using (
  exists (select 1 from public.user_profiles p where p.auth_user_id = auth.uid() and p.role_id = 1)
)
with check (
  exists (select 1 from public.user_profiles p where p.auth_user_id = auth.uid() and p.role_id = 1)
);
