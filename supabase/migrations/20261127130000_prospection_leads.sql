create table if not exists public.prospection_leads (
  id bigint generated by default as identity primary key,
  source_id text not null unique,
  name text not null,
  email text not null,
  gender text,
  status text,
  source text not null default 'configured_api',
  saved_by bigint,
  raw_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists prospection_leads_email_idx on public.prospection_leads (lower(email));
create index if not exists prospection_leads_saved_by_idx on public.prospection_leads (saved_by);

alter table public.prospection_leads enable row level security;
revoke all on public.prospection_leads from anon, authenticated;

notify pgrst, 'reload schema';
