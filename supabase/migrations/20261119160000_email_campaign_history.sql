-- Persistent email campaign history. Content and delivery statistics are stored server-side.
create table if not exists public.email_campaigns (
  id bigint generated by default as identity primary key,
  smtp_account_id bigint references public.smtp_accounts(id) on delete set null,
  liste_id bigint references public.listes(id) on delete set null,
  created_by bigint references public.user_profiles(id) on delete set null,
  sender_email text not null,
  sender_name text,
  liste_nom text not null,
  subject text not null,
  message text not null,
  recipients jsonb not null default '[]'::jsonb,
  failed_recipients jsonb not null default '[]'::jsonb,
  total_recipients integer not null default 0,
  sent_count integer not null default 0,
  failed_count integer not null default 0,
  status text not null default 'pending' check (status in ('pending', 'sent', 'partial', 'failed')),
  sent_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists email_campaigns_created_at_idx on public.email_campaigns (created_at desc);
create index if not exists email_campaigns_created_by_idx on public.email_campaigns (created_by);
alter table public.email_campaigns enable row level security;
drop policy if exists "email_campaigns_no_direct_access" on public.email_campaigns;
create policy "email_campaigns_no_direct_access" on public.email_campaigns
for all to authenticated using (false) with check (false);
-- Access is exclusively through authenticated server routes using the service role.
