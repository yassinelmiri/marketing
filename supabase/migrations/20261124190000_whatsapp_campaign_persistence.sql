-- Durable, per-user WhatsApp assisted campaigns and recipient progress.
begin;

create table if not exists public.whatsapp_campaigns (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 160),
  source_file text not null default '',
  message text not null default '',
  consent_confirmed_at timestamptz,
  status text not null default 'draft'
    check (status in ('draft','in_progress','paused','completed')),
  total_recipients integer not null default 0 check (total_recipients >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.whatsapp_campaign_recipients (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.whatsapp_campaigns(id) on delete cascade,
  contact_name text not null default '',
  phone text not null,
  status text not null default 'pending'
    check (status in ('pending','opened','sent','failed','skipped')),
  updated_at timestamptz not null default now(),
  unique (campaign_id, phone)
);

create index if not exists whatsapp_campaigns_user_updated_idx
  on public.whatsapp_campaigns(user_id, updated_at desc);
create index if not exists whatsapp_campaign_recipients_campaign_idx
  on public.whatsapp_campaign_recipients(campaign_id, id);

alter table public.whatsapp_campaigns enable row level security;
alter table public.whatsapp_campaign_recipients enable row level security;

drop policy if exists whatsapp_campaigns_no_direct_access on public.whatsapp_campaigns;
create policy whatsapp_campaigns_no_direct_access
  on public.whatsapp_campaigns for all to authenticated
  using (false) with check (false);

drop policy if exists whatsapp_campaign_recipients_no_direct_access on public.whatsapp_campaign_recipients;
create policy whatsapp_campaign_recipients_no_direct_access
  on public.whatsapp_campaign_recipients for all to authenticated
  using (false) with check (false);

commit;
