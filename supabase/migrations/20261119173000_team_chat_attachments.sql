-- Private team-chat attachments. All file operations go through authenticated server routes.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'team-chat-private',
  'team-chat-private',
  false,
  10485760,
  array['image/jpeg','image/png','image/webp','image/gif','application/pdf','text/plain','application/vnd.openxmlformats-officedocument.wordprocessingml.document','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet']
)
on conflict (id) do update set
  public = false,
  file_size_limit = 10485760,
  allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.team_chat_attachments (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  message_id bigint references public.team_chat_messages(id) on delete cascade,
  file_name text not null check (length(file_name) between 1 and 180),
  storage_path text not null unique,
  mime_type text not null,
  file_size bigint not null check (file_size > 0 and file_size <= 10485760),
  created_at timestamptz not null default now()
);
create index if not exists team_chat_attachments_message_idx
  on public.team_chat_attachments(message_id, created_at);
alter table public.team_chat_attachments enable row level security;
drop policy if exists team_chat_attachments_no_direct_access on public.team_chat_attachments;
create policy team_chat_attachments_no_direct_access
  on public.team_chat_attachments for all to authenticated
  using (false) with check (false);
