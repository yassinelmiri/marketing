-- Queue table used by the email campaign scheduler and delivery history.
-- Apply this migration to the Supabase project before creating/sending campaigns.

create table if not exists public.email_campaign_recipients (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.email_campaigns(id) on delete cascade,
  email text not null,
  status text not null default 'pending'
    check (status in ('pending', 'sent', 'failed', 'skipped')),
  error_message text,
  processed_at timestamptz,
  smtp_account_id bigint references public.smtp_accounts(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint email_campaign_recipients_campaign_email_key unique (campaign_id, email)
);

create index if not exists email_campaign_recipients_campaign_status_id_idx
  on public.email_campaign_recipients (campaign_id, status, id);

create index if not exists email_campaign_recipients_campaign_id_idx
  on public.email_campaign_recipients (campaign_id);

alter table public.email_campaign_recipients enable row level security;

revoke all on table public.email_campaign_recipients from anon, authenticated;
grant all on table public.email_campaign_recipients to service_role;
grant usage, select on sequence public.email_campaign_recipients_id_seq to service_role;

-- Refresh PostgREST's schema cache so the new table is immediately discoverable.
notify pgrst, 'reload schema';
