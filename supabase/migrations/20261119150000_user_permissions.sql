-- A per-user row overrides the corresponding role permission, including explicit denial.
create or replace function public.has_permission(permission_code text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  current_profile_id bigint;
  current_role_id bigint;
  requested_permission_id bigint;
  explicit_grant boolean;
begin
  if auth.uid() is null then
    return false;
  end if;

  if public.is_admin() then
    return true;
  end if;

  select id, role_id
    into current_profile_id, current_role_id
  from public.user_profiles
  where auth_user_id = auth.uid()
  limit 1;

  if current_profile_id is null then
    return false;
  end if;

  select id
    into requested_permission_id
  from public.permissions
  where code = permission_code
  limit 1;

  if requested_permission_id is null then
    return false;
  end if;

  select granted
    into explicit_grant
  from public.user_permissions
  where user_id = current_profile_id
    and permission_id = requested_permission_id;

  if found then
    return explicit_grant;
  end if;

  return exists (
    select 1
    from public.role_permissions
    where role_id = current_role_id
      and permission_id = requested_permission_id
  );
end;
$$;

grant execute on function public.has_permission(text) to authenticated;
