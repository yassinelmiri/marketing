-- Per-user module permissions. Safe to apply when user_permissions already exists.

create table if not exists public.user_permissions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  permission_id bigint not null references public.permissions(id) on delete cascade,
  granted boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_permissions_user_permission_unique unique (user_id, permission_id)
);

alter table public.user_permissions
  add column if not exists granted boolean not null default true;

alter table public.user_permissions enable row level security;

drop policy if exists "user_permissions_select_authenticated" on public.user_permissions;
drop policy if exists "user_permissions_select_own_or_admin" on public.user_permissions;
create policy "user_permissions_select_own_or_admin"
on public.user_permissions
for select
to authenticated
using (
  user_id = public.my_profile_id()
  or public.is_admin()
);

drop policy if exists "user_permissions_admin_insert" on public.user_permissions;
create policy "user_permissions_admin_insert"
on public.user_permissions
for insert
to authenticated
with check (public.is_admin());

drop policy if exists "user_permissions_admin_update" on public.user_permissions;
create policy "user_permissions_admin_update"
on public.user_permissions
for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "user_permissions_admin_delete" on public.user_permissions;
create policy "user_permissions_admin_delete"
on public.user_permissions
for delete
to authenticated
using (public.is_admin());

create index if not exists user_permissions_user_id_idx
on public.user_permissions(user_id);

