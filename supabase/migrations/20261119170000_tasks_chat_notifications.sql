-- Tasks, assignments, notifications and realtime team chat.
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 160),
  description text not null default '',
  priority text not null default 'medium' check (priority in ('low','medium','high','urgent')),
  status text not null default 'todo' check (status in ('todo','in_progress','waiting','done')),
  due_date date,
  created_by bigint references public.user_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.task_assignments (
  task_id bigint not null references public.tasks(id) on delete cascade,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  assigned_at timestamptz not null default now(),
  primary key(task_id,user_id)
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  type text not null,
  title text not null,
  body text not null default '',
  task_id bigint references public.tasks(id) on delete cascade,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists task_assignments_user_idx on public.task_assignments(user_id);
create index if not exists tasks_due_date_idx on public.tasks(due_date);
create index if not exists notifications_user_unread_idx on public.notifications(user_id,is_read,created_at desc);
create table if not exists public.team_chat_messages (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_profiles(id) on delete cascade,
  message text not null check (length(trim(message)) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists team_chat_created_idx on public.team_chat_messages(created_at desc);

alter table public.tasks enable row level security;
alter table public.task_assignments enable row level security;
alter table public.notifications enable row level security;
alter table public.team_chat_messages enable row level security;

-- These tables are accessed through server routes after identity/role validation.
drop policy if exists tasks_no_direct_access on public.tasks;
create policy tasks_no_direct_access on public.tasks for all to authenticated using (false) with check (false);
drop policy if exists task_assignments_no_direct_access on public.task_assignments;
create policy task_assignments_no_direct_access on public.task_assignments for all to authenticated using (false) with check (false);
drop policy if exists notifications_no_direct_access on public.notifications;
create policy notifications_no_direct_access on public.notifications for all to authenticated using (false) with check (false);
drop policy if exists team_chat_no_direct_access on public.team_chat_messages;
create policy team_chat_no_direct_access on public.team_chat_messages for all to authenticated using (false) with check (false);\n-- Realtime subscribers can read team messages; sending remains server-route-only.\ndrop policy if exists team_chat_realtime_read on public.team_chat_messages;\ncreate policy team_chat_realtime_read on public.team_chat_messages for select to authenticated using (true);\ndrop policy if exists notifications_realtime_read_own on public.notifications;\ncreate policy notifications_realtime_read_own on public.notifications for select to authenticated using (user_id = public.my_profile_id());

-- Enable Supabase Realtime on chat/notifications tables where the publication exists.
do $$
begin
  if exists(select 1 from pg_publication where pubname='supabase_realtime') then
    if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='team_chat_messages') then
      alter publication supabase_realtime add table public.team_chat_messages;
    end if;
    if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='notifications') then
      alter publication supabase_realtime add table public.notifications;
    end if;
  end if;
end $$;
