-- Extended email marketing suite: campaign settings, reusable templates,
-- recipient-level tracking, and global unsubscribe suppression.
begin;

alter table public.email_campaigns
  add column if not exists reply_to text,
  add column if not exists tracking_opens boolean not null default true,
  add column if not exists tracking_clicks boolean not null default true,
  add column if not exists unsubscribe_enabled boolean not null default true,
  add column if not exists batch_size integer not null default 25,
  add column if not exists batch_delay_seconds integer not null default 2,
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.email_templates (
  id bigint generated by default as identity primary key,
  name text not null,
  subject text not null default '',
  content text not null default '',
  created_by bigint references public.user_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists email_templates_created_at_idx on public.email_templates(created_at desc);
alter table public.email_templates enable row level security;
drop policy if exists "email_templates_no_direct_access" on public.email_templates;
create policy "email_templates_no_direct_access" on public.email_templates
for all to authenticated using (false) with check (false);

create table if not exists public.email_unsubscribes (
  id bigint generated by default as identity primary key,
  email text not null,
  unsubscribed_at timestamptz not null default now(),
  source text not null default 'manual',
  unique (email)
);
create index if not exists email_unsubscribes_email_idx on public.email_unsubscribes(lower(email));
alter table public.email_unsubscribes enable row level security;
drop policy if exists "email_unsubscribes_no_direct_access" on public.email_unsubscribes;
create policy "email_unsubscribes_no_direct_access" on public.email_unsubscribes
for all to authenticated using (false) with check (false);

create table if not exists public.email_campaign_recipients (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.email_campaigns(id) on delete cascade,
  email text not null,
  tracking_token text not null unique,
  sent_at timestamptz,
  opened_at timestamptz,
  clicked_at timestamptz,
  created_at timestamptz not null default now(),
  unique (campaign_id, email)
);
create index if not exists email_campaign_recipients_campaign_idx on public.email_campaign_recipients(campaign_id);
create index if not exists email_campaign_recipients_token_idx on public.email_campaign_recipients(tracking_token);
alter table public.email_campaign_recipients enable row level security;
drop policy if exists "email_campaign_recipients_no_direct_access" on public.email_campaign_recipients;
create policy "email_campaign_recipients_no_direct_access" on public.email_campaign_recipients
for all to authenticated using (false) with check (false);

commit;
